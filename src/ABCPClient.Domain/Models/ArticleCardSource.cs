namespace ABCPClient.Domain.Models;

/// <summary>
/// Откуда получена карточка товара.
/// </summary>
/// <remarks>
/// Источник важен потому, что обращения к API ограничены по частоте (ошибка 303),
/// а выгрузка каталога магазина даёт те же данные бесплатно и пакетом.
/// </remarks>
public enum ArticleCardSource
{
    /// <summary>Карточка получена запросом к API ABCP.</summary>
    Api = 0,

    /// <summary>Карточка получена из выгрузки каталога магазина (YML).</summary>
    Catalog = 1,

    /// <summary>
    /// Карточка получена со страницы товара на витрине магазина.
    /// </summary>
    /// <remarks>
    /// Витрина — обычный сайт, а не API: её страницы лимит вызовов API не расходуют.
    /// Так добираются детали под заказ, которых в выгрузке каталога нет.
    /// </remarks>
    Storefront = 2,
}
