namespace ABCPClient.Application.Configuration;

/// <summary>
/// Параметры импорта каталога магазина из выгрузки YML.
/// </summary>
/// <remarks>
/// Выгрузка каталога — бесплатный источник карточек товаров: в ней есть описания,
/// свойства, изображения и штрихкоды по всему ассортименту магазина. Импорт заполняет
/// кэш карточек одним файлом, и обращения к API остаются только для чужих артикулов,
/// которых в каталоге нет.
/// </remarks>
public sealed class CatalogOptions
{
    /// <summary>Имя секции в конфигурации.</summary>
    public const string SectionName = "Catalog";

    /// <summary>
    /// Путь к файлу выгрузки или её адрес в сети. Адрес указывает на витрину магазина,
    /// а не на API, поэтому лимит вызовов API он не расходует.
    /// </summary>
    public string FeedPath { get; set; } = string.Empty;

    /// <summary>
    /// Обновлять каталог автоматически раз в столько часов. Ноль — только вручную.
    /// </summary>
    public int AutoImportHours { get; set; }

    /// <summary>
    /// Адрес витрины магазина, например <c>https://da174.ru</c>. Пусто — источник выключен.
    /// </summary>
    /// <remarks>
    /// В выгрузке каталога только собственное наличие, а заказы почти целиком состоят
    /// из деталей под заказ. Их карточки берутся со страницы товара на витрине:
    /// это обычный сайт, лимит вызовов API он не расходует.
    /// </remarks>
    public string StorefrontUrl { get; set; } = string.Empty;

    /// <summary>
    /// Сколько страниц витрины разрешено запрашивать в минуту.
    /// </summary>
    public int StorefrontRequestsPerMinute { get; set; } = 60;

    /// <summary>
    /// Заранее скачивать изображения импортированных карточек.
    /// </summary>
    /// <remarks>
    /// Изображения лежат на CDN, а не на API, поэтому массовая загрузка безопасна.
    /// Занимает место на диске: несколько тысяч файлов.
    /// </remarks>
    public bool PrefetchImages { get; set; }
}
